#!/usr/bin/env python3
"""Generate the app and site design tokens from brand/tokens.json.

Writes Tokens.kt (Android) and tokens.css (site). With --check nothing is written:
the exit code is 1 when a file differs from what a fresh run would write.
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_TOKENS = ROOT / "brand" / "tokens.json"
DEFAULT_KOTLIN = ROOT / "android/app/src/main/kotlin/app/rustmfa/android/ui/design/Tokens.kt"
DEFAULT_CSS = ROOT / "site" / "tokens.css"
DEFAULT_GUIDE = ROOT / "brand" / "GUIDE.md"
GUIDE_START = "<!-- tokens:start -->"
GUIDE_END = "<!-- tokens:end -->"

COLOR_KEYS = ["rost500", "rost600", "rost700", "action", "onAction", "ink", "slate", "paper", "surface", "ok", "danger"]
GRADIENT_KEYS = ["markStart", "markEnd", "iconStart", "iconEnd", "tabStart", "tabEnd"]
SIZE_KEYS = ["headline", "title", "body", "label", "caption"]
RADIUS_KEYS = ["chip", "card", "sheet", "button"]
HEX = re.compile(r"^#[0-9A-Fa-f]{6}$")


class TokenError(Exception):
    pass


def _need(data, path):
    node = data
    for part in path:
        if not isinstance(node, dict) or part not in node:
            raise TokenError("missing key: " + ".".join(path))
        node = node[part]
    return node


def _hex(data, path):
    value = _need(data, path)
    if not isinstance(value, str) or not HEX.match(value):
        raise TokenError("not a #RRGGBB colour: %s = %r" % (".".join(path), value))
    return value.upper()


def _int(data, path):
    value = _need(data, path)
    if not isinstance(value, int) or isinstance(value, bool) or value <= 0:
        raise TokenError("not a positive integer: %s = %r" % (".".join(path), value))
    return value


def validate(data):
    """Return a normalised copy of the tokens or raise TokenError naming the bad key."""
    out = {"colors": {}, "gradient": {}, "sizes": {}, "radius": {}}
    for theme in ("light", "dark"):
        _need(data, ["colors", theme])
        out["colors"][theme] = {k: _hex(data, ["colors", theme, k]) for k in COLOR_KEYS}
    out["gradient"] = {k: _hex(data, ["gradient", k]) for k in GRADIENT_KEYS}
    out["sizes"] = {k: _int(data, ["type", "sizes", k]) for k in SIZE_KEYS}
    out["radius"] = {k: _int(data, ["radius", k]) for k in RADIUS_KEYS}
    return out


def cap(name):
    return name[0].upper() + name[1:]


def kebab(name):
    return re.sub(r"([a-z])([A-Z0-9])", r"\1-\2", name).lower()


def kotlin_color(value):
    return "Color(0xFF%s)" % value[1:]


def render_kotlin(t):
    lines = [
        "// Generated by brand/generate.py from brand/tokens.json. Do not edit.",
        "package app.rustmfa.android.ui.design",
        "",
        "import androidx.compose.ui.graphics.Color",
        "import androidx.compose.ui.unit.Dp",
        "import androidx.compose.ui.unit.TextUnit",
        "import androidx.compose.ui.unit.dp",
        "import androidx.compose.ui.unit.sp",
        "",
        "object Tokens {",
    ]
    for theme in ("light", "dark"):
        lines.append("    object %s {" % cap(theme))
        for key in COLOR_KEYS:
            lines.append("        val %s = %s" % (key, kotlin_color(t["colors"][theme][key])))
        lines.append("    }")
    for key in GRADIENT_KEYS:
        lines.append("    val %s = %s" % (key, kotlin_color(t["gradient"][key])))
    for key in RADIUS_KEYS:
        lines.append("    val radius%s: Dp = %d.dp" % (cap(key), t["radius"][key]))
    for key in SIZE_KEYS:
        lines.append("    val size%s: TextUnit = %d.sp" % (cap(key), t["sizes"][key]))
    lines.append("}")
    return "\n".join(lines) + "\n"


def render_css(t):
    lines = ["/* Generated by brand/generate.py from brand/tokens.json. Do not edit. */", ":root {"]
    for key in COLOR_KEYS:
        lines.append("  --%s: %s;" % (kebab(key), t["colors"]["light"][key]))
    for key in GRADIENT_KEYS:
        lines.append("  --%s: %s;" % (kebab(key), t["gradient"][key]))
    for key in RADIUS_KEYS:
        lines.append("  --radius-%s: %dpx;" % (key, t["radius"][key]))
    for key in SIZE_KEYS:
        lines.append("  --size-%s: %dpx;" % (key, t["sizes"][key]))
    lines += ["}", "@media (prefers-color-scheme: dark) {", "  :root {"]
    for key in COLOR_KEYS:
        lines.append("    --%s: %s;" % (kebab(key), t["colors"]["dark"][key]))
    lines += ["  }", "}"]
    return "\n".join(lines) + "\n"


def render_guide_table(t):
    lines = ["### Colour", "", "| Token | Light | Dark |", "| --- | --- | --- |"]
    for key in COLOR_KEYS:
        lines.append("| `%s` | `%s` | `%s` |" % (key, t["colors"]["light"][key], t["colors"]["dark"][key]))
    lines += ["", "### Gradients", "", "| Token | Value |", "| --- | --- |"]
    for key in GRADIENT_KEYS:
        lines.append("| `%s` | `%s` |" % (key, t["gradient"][key]))
    lines += ["", "### Type scale", "", "| Name | Size (sp) |", "| --- | --- |"]
    for key in SIZE_KEYS:
        lines.append("| `%s` | %d |" % (key, t["sizes"][key]))
    lines += ["", "### Radii", "", "| Name | Size (dp) |", "| --- | --- |"]
    for key in RADIUS_KEYS:
        lines.append("| `%s` | %d |" % (key, t["radius"][key]))
    return "\n".join(lines) + "\n"


def apply_guide(text, table):
    """Replace what is between the two markers; everything else stays byte for byte."""
    a, b = text.find(GUIDE_START), text.find(GUIDE_END)
    if a < 0 or b < a:
        raise TokenError("the guide has no %s ... %s block" % (GUIDE_START, GUIDE_END))
    return text[: a + len(GUIDE_START)] + "\n" + table + text[b:]


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--check", action="store_true")
    p.add_argument("--tokens", type=Path, default=DEFAULT_TOKENS)
    p.add_argument("--kotlin-out", type=Path, default=DEFAULT_KOTLIN)
    p.add_argument("--css-out", type=Path, default=DEFAULT_CSS)
    p.add_argument("--guide-out", type=Path, default=DEFAULT_GUIDE)
    args = p.parse_args(argv)
    try:
        tokens = validate(json.loads(args.tokens.read_text()))
    except (TokenError, OSError, ValueError) as e:
        print("tokens error: %s" % e, file=sys.stderr)
        return 1
    try:
        guide_text = apply_guide(args.guide_out.read_text(), render_guide_table(tokens))
    except (TokenError, OSError) as e:
        print("guide error: %s" % e, file=sys.stderr)
        return 1
    outputs = [(args.kotlin_out, render_kotlin(tokens)), (args.css_out, render_css(tokens)), (args.guide_out, guide_text)]
    if args.check:
        stale = [str(path) for path, text in outputs if not path.exists() or path.read_text() != text]
        for name in stale:
            print("out of date: %s (run brand/generate.py)" % name, file=sys.stderr)
        return 1 if stale else 0
    for path, text in outputs:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
